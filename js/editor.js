let project=null, selected=null, pendingAdd=false;
let drag=null, directionDrag=null;
let planScale=1, panX=0, panY=0;
let fitScale=1;
let planReady=false;
let resizeObserver=null;
let pinchStartDistance=null, pinchStartScale=1, panStart=null;

const $=id=>document.getElementById(id);

async function init(){
  const r=await fetch('data/project.json?ts='+Date.now());
  if(!r.ok) throw Error('Cannot load data/project.json');
  project=await r.json();
  setupFloors();
  scanPanoramas();
  renderEditor();
  setupGestures();
  setupPlanResizeObserver();
}

function setupFloors(){
  const s=$('floorSelect');
  s.innerHTML='';
  project.floors.forEach((f,i)=>{
    const o=document.createElement('option');
    o.value=i;
    o.textContent=f.name||f.id;
    s.appendChild(o);
  });
  s.onchange=()=>{
    selected=null;
    pendingAdd=false;
    resetPlanTransform();
    renderEditor();
    hideForm();
  };
}

function currentFloor(){ return project.floors[Number($('floorSelect').value)||0]; }

function scanPanoramas(){
  // The browser cannot directly list a folder. scenes.js is generated by
  // tools/generate_scenes.py and contains the REAL panorama filenames.
  const sceneList=Array.isArray(window.TRIPT_SCENES)?window.TRIPT_SCENES:[];
  const assigned=[];
  (project.floors||[]).forEach(f=>{
    (f.views||[]).forEach(v=>{
      if(v.panorama) assigned.push(v.panorama);
    });
  });

  const paths=[];
  sceneList.forEach(scene=>{
    const path=scene.file && String(scene.file).startsWith('assets/')
      ? scene.file
      : 'assets/panoramas/'+scene.file;
    if(path && !paths.includes(path)) paths.push(path);
  });

  // Keep old/saved assignments visible even if scenes.js has not been regenerated.
  assigned.forEach(path=>{
    if(path && !paths.includes(path)) paths.push(path);
  });

  const sel=$('panoramaSelect');
  sel.innerHTML='';
  paths.forEach(path=>{
    const o=document.createElement('option');
    o.value=path;
    o.textContent=path.split('/').pop(); // show the actual filename only
    sel.appendChild(o);
  });
}

function renderEditor(){
  const f=currentFloor();
  const img=$('editorPlanImage');
  planReady=false;
  img.onload=()=>{
    preparePlanSize();
    resetPlanTransform();
    planReady=true;
  };
  img.src=f.plan;

  const layer=$('editorMarkers');
  layer.innerHTML='';

  (f.views||[]).forEach(v=>{
    const m=document.createElement('div');
    m.className='marker'+(selected&&selected.id===v.id?' selected':'');
    m.style.left=v.x+'%';
    m.style.top=v.y+'%';
    m.dataset.id=v.id;

    const d=document.createElement('button');
    d.type='button';
    d.className='direction';
    d.textContent='↑';
    d.style.transform='translateX(-50%) rotate('+(Number(v.heading)||0)+'deg)';
    d.onpointerdown=e=>{
      e.preventDefault();
      e.stopPropagation();
      startDirection(e,v,m);
    };
    m.appendChild(d);

    const lab=document.createElement('div');
    lab.className='marker-label';
    lab.textContent=v.name||'360';
    m.appendChild(lab);

    m.onpointerdown=e=>{
      if(e.target===d) return;
      e.preventDefault();
      selectView(v);
      startDrag(e,v,m);
    };

    m.onclick=e=>{
      if(e.target===d) return;
      selectView(v);
    };

    layer.appendChild(m);
  });

  applyPlanTransform();
  updateCoordinates();
}

function selectView(v){
  selected=v;
  showForm();
  renderEditor();
  $('status').textContent='Selected: '+(v.name||'360 View');
}

function showForm(){
  if(!selected) return;
  $('noSelection').classList.add('hidden');
  $('viewForm').classList.remove('hidden');
  $('viewName').value=selected.name||'';
  $('panoramaSelect').value=selected.panorama||'';
  if(selected.panorama && $('panoramaSelect').value!==selected.panorama){
    const o=document.createElement('option');
    o.value=selected.panorama;
    o.textContent=selected.panorama.split('/').pop();
    $('panoramaSelect').appendChild(o);
    $('panoramaSelect').value=selected.panorama;
  }
  $('xPos').value=Number(selected.x||0).toFixed(2);
  $('yPos').value=Number(selected.y||0).toFixed(2);
  $('heading').value=selected.heading||0;
  updateCoordinates();
}

function hideForm(){
  $('noSelection').classList.remove('hidden');
  $('viewForm').classList.add('hidden');
}

function updateCoordinates(){
  if(!selected){
    $('liveCoordinates').textContent='X 0.00% | Y 0.00%';
    return;
  }
  $('liveCoordinates').textContent=
    `X ${Number(selected.x||0).toFixed(2)}% | Y ${Number(selected.y||0).toFixed(2)}%`;
}

$('addView').onclick=()=>{
  pendingAdd=true;
  $('status').textContent='Click a location on the plan to place the new view.';
};

$('editorPlan').addEventListener('click',e=>{
  if(!pendingAdd || e.target.closest('.marker')) return;

  const rect=$('editorPlanImage').getBoundingClientRect();
  const x=clamp((e.clientX-rect.left)/rect.width*100,0,100);
  const y=clamp((e.clientY-rect.top)/rect.height*100,0,100);

  const used=new Set((currentFloor().views||[]).map(v=>v.panorama));
  const options=[...$('panoramaSelect').options].map(o=>o.value);
  const pano=options.find(path=>!used.has(path))||options[0]||'';

  const v={
    id:'view-'+Date.now(),
    name:'New View',
    panorama:pano,
    x:+x.toFixed(2),
    y:+y.toFixed(2),
    heading:0
  };

  currentFloor().views.push(v);
  selected=v;
  pendingAdd=false;
  showForm();
  renderEditor();
  $('status').textContent='New view placed. Edit it and click Apply Changes.';
});

function apply(){
  if(!selected) return;

  selected.name=$('viewName').value.trim()||'360 View';
  selected.panorama=$('panoramaSelect').value;
  selected.x=clamp(+$('xPos').value,0,100);
  selected.y=clamp(+$('yPos').value,0,100);
  selected.heading=+$('heading').value||0;

  renderEditor();
  showForm();
  $('status').textContent='Changes applied.';
}
$('applyChanges').onclick=apply;

$('deleteView').onclick=()=>{
  if(!selected) return;
  const f=currentFloor();
  f.views=f.views.filter(v=>v.id!==selected.id);
  selected=null;
  hideForm();
  renderEditor();
  $('status').textContent='View deleted.';
};

$('xPos').oninput=()=>{
  if(!selected) return;
  selected.x=clamp(+$('xPos').value,0,100);
  updateCoordinates();
  updateSelectedMarker();
};
$('yPos').oninput=()=>{
  if(!selected) return;
  selected.y=clamp(+$('yPos').value,0,100);
  updateCoordinates();
  updateSelectedMarker();
};
$('heading').oninput=()=>{
  if(!selected) return;
  selected.heading=+$('heading').value||0;
  const m=document.querySelector(`.marker[data-id="${CSS.escape(selected.id)}"]`);
  if(m) m.querySelector('.direction').style.transform=
    'translateX(-50%) rotate('+selected.heading+'deg)';
};
$('viewName').oninput=()=>{
  if(!selected) return;
  const m=document.querySelector(`.marker[data-id="${CSS.escape(selected.id)}"]`);
  if(m) m.querySelector('.marker-label').textContent=$('viewName').value||'360 View';
};

function updateSelectedMarker(){
  if(!selected) return;
  const m=document.querySelector(`.marker[data-id="${CSS.escape(selected.id)}"]`);
  if(!m) return;
  m.style.left=selected.x+'%';
  m.style.top=selected.y+'%';
}

function startDrag(e,v,m){
  if(e.pointerType==='touch') m.setPointerCapture(e.pointerId);
  drag={v,m,pointerId:e.pointerId};
  m.onpointermove=moveDrag;
  m.onpointerup=endDrag;
  m.onpointercancel=endDrag;
}

function moveDrag(e){
  if(!drag) return;
  const rect=$('editorPlanImage').getBoundingClientRect();
  drag.v.x=clamp((e.clientX-rect.left)/rect.width*100,0,100);
  drag.v.y=clamp((e.clientY-rect.top)/rect.height*100,0,100);
  drag.m.style.left=drag.v.x+'%';
  drag.m.style.top=drag.v.y+'%';
  selected=drag.v;
  showForm();
  updateCoordinates();
}

function endDrag(){
  if(!drag) return;
  drag.m.onpointermove=null;
  drag.m.onpointerup=null;
  drag.m.onpointercancel=null;
  drag=null;
  $('status').textContent='Marker moved. Click Apply Changes to confirm.';
}

function startDirection(e,v,m){
  directionDrag={v,m,pointerId:e.pointerId};
  m.setPointerCapture(e.pointerId);
  m.onpointermove=moveDirection;
  m.onpointerup=endDirection;
  m.onpointercancel=endDirection;
}

function moveDirection(e){
  if(!directionDrag) return;
  const r=directionDrag.m.getBoundingClientRect();
  const cx=r.left+r.width/2, cy=r.top+r.height/2;
  let deg=Math.atan2(e.clientY-cy,e.clientX-cx)*180/Math.PI+90;
  deg=Math.round((deg+360)%360);
  if(deg>180) deg-=360;
  directionDrag.v.heading=deg;
  directionDrag.m.querySelector('.direction').style.transform=
    'translateX(-50%) rotate('+deg+'deg)';
  $('heading').value=deg;
}

function endDirection(){
  if(!directionDrag) return;
  directionDrag.m.onpointermove=null;
  directionDrag.m.onpointerup=null;
  directionDrag.m.onpointercancel=null;
  directionDrag=null;
  $('status').textContent='Direction changed. Click Apply Changes to confirm.';
}

function preparePlanSize(){
  const img=$('editorPlanImage');
  const stage=$('editorPlan');
  const viewport=$('editorPlanViewport');
  if(!img.naturalWidth || !img.naturalHeight || !viewport.clientWidth || !viewport.clientHeight) return;

  // Keep the stage at the image's native aspect ratio.
  // The transform below is responsible for fitting it into the viewport.
  stage.style.width=img.naturalWidth+'px';
  stage.style.height=img.naturalHeight+'px';

  const availableW=Math.max(80,viewport.clientWidth-8);
  const availableH=Math.max(80,viewport.clientHeight-8);
  fitScale=Math.min(
    availableW/img.naturalWidth,
    availableH/img.naturalHeight
  ) * 0.98;

  fitScale=Math.max(0.05,Math.min(fitScale,4));
}

function resetPlanTransform(){
  preparePlanSize();
  planScale=fitScale;
  panX=0;
  panY=0;
  applyPlanTransform();
}

function applyPlanTransform(){
  $('editorPlan').style.transform=
    `translate(${panX}px,${panY}px) scale(${planScale})`;
}

function setupPlanResizeObserver(){
  const viewport=$('editorPlanViewport');
  if(!viewport) return;

  const handleResize=()=>{
    if(!planReady) return;
    const oldFit=fitScale;
    preparePlanSize();
    // If the user is at the fitted view, refit after a screen/orientation change.
    if(Math.abs(planScale-oldFit)<0.015){
      planScale=fitScale;
      panX=0;
      panY=0;
      applyPlanTransform();
    }
  };

  if('ResizeObserver' in window){
    resizeObserver=new ResizeObserver(handleResize);
    resizeObserver.observe(viewport);
  }else{
    window.addEventListener('resize',handleResize);
  }
}

function setupGestures(){
  const viewport=$('editorPlanViewport');

  viewport.addEventListener('wheel',e=>{
    e.preventDefault();
    const factor=e.deltaY<0?1.08:0.92;
    planScale=clamp(planScale*factor,fitScale,4);
    applyPlanTransform();
  },{passive:false});

  let mousePan=false;
  let panStartX=0,panStartY=0,baseX=0,baseY=0;

  viewport.addEventListener('pointerdown',e=>{
    if(e.target.closest('.marker')) return;
    if(e.pointerType==='mouse' && e.button!==1) return;

    mousePan=true;
    panStartX=e.clientX;
    panStartY=e.clientY;
    baseX=panX;
    baseY=panY;
    viewport.setPointerCapture(e.pointerId);
  });

  viewport.addEventListener('pointermove',e=>{
    if(!mousePan) return;
    panX=baseX+e.clientX-panStartX;
    panY=baseY+e.clientY-panStartY;
    applyPlanTransform();
  });

  viewport.addEventListener('pointerup',()=>{
    mousePan=false;
  });

  viewport.addEventListener('touchstart',e=>{
    if(e.touches.length===2){
      pinchStartDistance=distance(e.touches[0],e.touches[1]);
      pinchStartScale=planScale;
      panStart={x:panX,y:panY};
    }
  },{passive:true});

  viewport.addEventListener('touchmove',e=>{
    if(e.touches.length===2 && pinchStartDistance){
      const d=distance(e.touches[0],e.touches[1]);
      planScale=clamp(pinchStartScale*d/pinchStartDistance,fitScale,4);
      applyPlanTransform();
    }
  },{passive:true});

  viewport.addEventListener('touchend',()=>{
    pinchStartDistance=null;
  });
}

function distance(a,b){
  return Math.hypot(a.clientX-b.clientX,a.clientY-b.clientY);
}

function clamp(n,a,b){
  return Number.isFinite(n)?Math.max(a,Math.min(b,n)):a;
}

$('saveProject').onclick=()=>{
  if(selected) apply();

  const blob=new Blob([JSON.stringify(project,null,2)],{type:'application/json'});
  const url=URL.createObjectURL(blob);
  const a=document.createElement('a');
  a.href=url;
  a.download='project.json';
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(()=>URL.revokeObjectURL(url),1000);

  $('status').textContent=
    'project.json downloaded. Replace data/project.json with it.';
};

$('resetView').onclick=()=>{
  resetPlanTransform();
};

window.addEventListener('load',()=>init().catch(e=>{
  console.error(e);
  alert(e.message);
}));
